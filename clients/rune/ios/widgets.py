"""Build and embed the widget extension: the Lock Screen card, the Dynamic
Island and the agents widget (Widgets/, Shared/). Built only for an identity
that names an App Group, which both bundles must be signed with."""

import json
from pathlib import Path
import plistlib
import shutil

IOS = Path(__file__).resolve().parent
NAME = "PhuxWidgets"
# An App ID the App Store app already registered: renaming it would drop the
# widgets people placed.
SUFFIX = ".agentstatus"


def extension_plist(identity, simulator, minimum_ios):
    return {
        "CFBundleIdentifier": identity["bundle_id"] + SUFFIX, "CFBundleExecutable": NAME,
        "CFBundleName": NAME, "CFBundleDisplayName": identity["display_name"],
        "CFBundlePackageType": "XPC!", "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleShortVersionString": identity["version"], "CFBundleVersion": identity["build_number"],
        "MinimumOSVersion": minimum_ios, "UIDeviceFamily": [1],
        "CFBundleSupportedPlatforms": ["iPhoneSimulator" if simulator else "iPhoneOS"],
        "PhuxAppGroup": identity["app_group"],
        "NSExtension": {"NSExtensionPointIdentifier": "com.apple.widgetkit-extension"},
    }


def compile_assets(out, env, run, appex, simulator, minimum_ios):
    catalog = out / "Widgets.xcassets"
    if catalog.exists():
        shutil.rmtree(catalog)  # Our derived catalog, never a source tree.
    # Generated by `just design-gen`; never edited here.
    shutil.copytree(IOS / "Widgets/Assets", catalog)
    (catalog / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}))
    run(["/usr/bin/xcrun", "actool", catalog, "--compile", appex, "--platform",
         "iphonesimulator" if simulator else "iphoneos", "--minimum-deployment-target", minimum_ios,
         "--target-device", "iphone", "--errors", "--warnings"], env, out, "widget-assets", timeout=300)


def embed(app, out, env, run, identity, simulator, release, minimum_ios, entitlements):
    sources = sorted([*(IOS / "Widgets/Sources").glob("*.swift"), *(IOS / "Shared").glob("*.swift")])
    appex = app / "PlugIns" / f"{NAME}.appex"
    appex.mkdir(parents=True)
    sdk = "iphonesimulator" if simulator else "iphoneos"
    sdk_path = run(["/usr/bin/xcrun", "--sdk", sdk, "--show-sdk-path"],
                   env, out, "widget-sdk", stdout_only=True).strip()
    target = f"arm64-apple-ios{minimum_ios}" + ("-simulator" if simulator else "")
    flags = ["-e", "_NSExtensionMain"]
    if simulator:
        flags += ["-sectcreate", "__TEXT", "__entitlements", str(entitlements)]
    run(["/usr/bin/xcrun", "--sdk", sdk, "swiftc", "-swift-version", "6", "-strict-concurrency=complete",
         "-warnings-as-errors", "-target", target, "-sdk", sdk_path, "-module-cache-path", out / "module-cache",
         "-module-name", NAME, "-application-extension", "-parse-as-library", "-O" if release else "-Onone",
         *sources, *[arg for flag in flags for arg in ("-Xlinker", flag)], "-o", appex / NAME],
        env, out, "widget-swift", timeout=600)
    compile_assets(out, env, run, appex, simulator, minimum_ios)
    (appex / "Info.plist").write_bytes(plistlib.dumps(extension_plist(identity, simulator, minimum_ios)))
    if simulator:
        run(["/usr/bin/codesign", "--force", "--sign", "-", "--timestamp=none", appex], env, out, "sign-widgets")
    return appex
