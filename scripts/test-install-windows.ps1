#Requires -Version 5.1
# Dependency-free installer/launcher contract tests (PowerShell 5.1 and 7).
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$installer = Join-Path $PSScriptRoot 'install-windows.ps1'
$work = Join-Path ([IO.Path]::GetTempPath()) ('phux-windows-test-' + [Guid]::NewGuid().ToString('N'))
$originalOS = $env:OS

function Assert-True([bool] $Condition, [string] $Message) {
    if (-not $Condition) { throw $Message }
}

function Assert-Throws([scriptblock] $Action, [string] $Pattern) {
    try { & $Action } catch {
        Assert-True ($_.Exception.Message -match $Pattern) "Unexpected error: $_"
        return
    }
    throw "Expected failure matching $Pattern"
}

try {
    # Dry-run loads the same functions that are embedded in installed launchers.
    $env:OS = 'Windows_NT'
    $bin = Join-Path $work 'bin with spaces'
    . $installer -InstallDir $bin -DryRun | Out-Null
    Assert-True (-not (Test-Path $work)) 'Dry-run wrote files'
    Assert-Throws { ConvertTo-PhuxShellLiteral ("NUL" + [char]0) } 'cannot contain NUL'
    Assert-True (Test-PhuxTui phux @()) 'Bare phux must preserve native console I/O'
    Assert-True (Test-PhuxTui phux @('--socket', '/tmp/test', 'attach', 'work')) 'Attach classification failed'
    Assert-True (Test-PhuxTui phux @('--socket=/tmp/test', 'a', 'work')) 'Attach alias classification failed'
    Assert-True (Test-PhuxTui phux @('--rec', 'out.cast', '--remote', 'host')) 'Root attach flags classification failed'
    Assert-True (Test-PhuxTui phux @('new', 'work')) 'New session classification failed'
    Assert-True (Test-PhuxTui phux @('project', 'open', 'work')) 'Project attach classification failed'
    Assert-True (Test-PhuxTui phux @('host', 'attach', 'work')) 'Host attach classification failed'
    Assert-True (Test-PhuxTui phux @('worktree', 'open', 'work', '--attach')) 'Worktree attach classification failed'
    Assert-True (-not (Test-PhuxTui phux @('new', '--json', '-s', 'work'))) 'JSON commands must retain UTF-8 capture'
    Assert-True (-not (Test-PhuxTui phux @('run', '@1', 'attach'))) 'Command data was mistaken for the root verb'
    Assert-True (-not (Test-PhuxTui phux @('project', 'list'))) 'Project list is headless'
    Assert-True (-not (Test-PhuxTui phux @('--help'))) 'Help is headless'
    Assert-True (-not (Test-PhuxTui phux-mcp @())) 'MCP is not an interactive TUI'
    Assert-Throws { & $installer -InstallDir $bin -Channel next -Version 1.2.3 } 'requires -Channel stable'
    Assert-Throws { & $installer -InstallDir ' ' } 'must not be empty'
    Assert-Throws { & $installer -Distribution '--exec' -DryRun } 'pattern'
    $env:OS = 'not-Windows'
    Assert-Throws { & $installer -InstallDir $bin -DryRun } 'Windows PowerShell'
    $env:OS = 'Windows_NT'

    $global:PhuxTestInvocations = @()
    $global:PhuxTestWslResult = 0
    $global:PhuxTestWslResults = [Collections.Generic.Queue[int]]::new()
    function wsl.exe {
        $global:PhuxTestInvocations += ,@($args)
        if ($global:PhuxTestWslResults.Count) {
            $global:LASTEXITCODE = $global:PhuxTestWslResults.Dequeue()
        } else { $global:LASTEXITCODE = $global:PhuxTestWslResult }
    }

    # Failed Linux installation must not touch existing Windows launchers.
    [IO.Directory]::CreateDirectory($bin) | Out-Null
    $existing = Join-Path $bin 'phux.ps1'
    [IO.File]::WriteAllText($existing, 'sentinel')
    Assert-Throws { & $installer -InstallDir $bin -NoModifyPath } 'unrelated file'
    [IO.File]::WriteAllText($existing, "# Generated by phux's WSL installer.`nsentinel")
    $global:PhuxTestWslResult = 1
    Assert-Throws { & $installer -InstallDir $bin -NoModifyPath } 'non-root default user'
    Assert-True ([IO.File]::ReadAllText($existing).EndsWith('sentinel')) 'Failed preflight changed a launcher'

    $companion = Join-Path $bin 'phux-mcp.ps1'
    [IO.File]::WriteAllText($companion, "# Generated by phux's WSL installer.`ncompanion sentinel")
    $beforeCli = [IO.File]::ReadAllText($existing)
    $beforeMcp = [IO.File]::ReadAllText($companion)
    $beforePath = $env:Path
    $beforeUserPath = [Environment]::GetEnvironmentVariable('Path', 'User')
    $global:PhuxTestWslResults.Enqueue(0)
    $global:PhuxTestWslResults.Enqueue(1)
    Assert-Throws { & $installer -InstallDir $bin } 'Linux release installation failed'
    Assert-True ([IO.File]::ReadAllText($existing) -ceq $beforeCli) 'Failed installation changed CLI launcher'
    Assert-True ([IO.File]::ReadAllText($companion) -ceq $beforeMcp) 'Failed installation changed MCP launcher'
    Assert-True ($env:Path -ceq $beforePath) 'Failed installation changed process PATH'
    Assert-True ([Environment]::GetEnvironmentVariable('Path', 'User') -ceq $beforeUserPath) 'Failed installation changed user PATH'

    $global:PhuxTestWslResult = 0
    $crlfInstaller = Join-Path $work 'install-crlf.ps1'
    $crlf = [IO.File]::ReadAllText($installer).Replace("`r`n", "`n").Replace("`n", "`r`n")
    [IO.File]::WriteAllText($crlfInstaller, $crlf)
    & $crlfInstaller -InstallDir $bin -Distribution 'Ubuntu-24.04' -Version 1.2.3 -NoModifyPath | Out-Null
    Assert-True ($global:PhuxTestInvocations.Count -eq 5) 'Expected preflight, failed installation and successful installation'
    $installArgs = $global:PhuxTestInvocations[-1]
    Assert-True ($installArgs[1] -eq 'Ubuntu-24.04') 'Distribution was not selected'
    Assert-True ($installArgs[-1] -notmatch '"') 'Native argument contains embedded double quotes'
    $encoded = [regex]::Match($installArgs[-1], 'printf %s ([A-Za-z0-9+/=]+)\|').Groups[1].Value
    $decoded = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($encoded))
    Assert-True (-not $decoded.Contains("`r")) 'Windows checkout injected CRLF into Linux shell source'
    Assert-True ($decoded.Contains('--install-dir "$HOME/.local/bin"')) 'Launcher and Linux installation paths disagree'
    foreach ($tool in @('phux', 'phux-mcp')) {
        $file = Join-Path $bin ($tool + '.ps1')
        Assert-True (Test-Path $file) "Missing $tool launcher"
        $tokens = $null
        $errors = $null
        [Management.Automation.Language.Parser]::ParseFile($file, [ref] $tokens, [ref] $errors) | Out-Null
        Assert-True ($errors.Count -eq 0) "Generated $tool launcher does not parse: $errors"
        Assert-True ([IO.File]::ReadAllText($file).Contains("`$tool = '$tool'")) 'Wrong tool selected'
    }

    # On Unix, exercise the actual decoded shell payload, not a model of it.
    # The Windows CI lane repeats this through real wsl.exe in both PS hosts.
    if ($originalOS -ne 'Windows_NT') {
        $values = @('', 'two words', 'single''quote', 'double"quote', 'back\slash\',
            '$HOME; touch NOPE', '*?[abc]', "line`nbreak", ('"\ud83c\udf55"' | ConvertFrom-Json), '-n', 'C:\a b\')
        $command = "printf '%s\n'"
        foreach ($value in $values) { $command += ' ' + (ConvertTo-PhuxShellLiteral $value) }
        $payload = (Get-PhuxWslArguments Ubuntu $command)[-1]
        $actual = @(& sh -c $payload)
        $expected = ($values -join "`n") -split "`n"
        Assert-True (($actual -join "`n") -ceq ($expected -join "`n")) 'Shell quoting changed argument data'
        Assert-True (-not (Test-Path (Join-Path $root 'NOPE'))) 'Shell injection was executed'
    }
    Write-Output 'Windows installer contracts passed.'
} finally {
    $env:OS = $originalOS
    Remove-Variable PhuxTestInvocations, PhuxTestWslResult, PhuxTestWslResults -Scope Global -ErrorAction SilentlyContinue
    if (Test-Path $work) { Remove-Item -LiteralPath $work -Recurse -Force }
}
