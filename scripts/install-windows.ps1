#Requires -Version 5.1
<#
.SYNOPSIS
Install phux in WSL and expose phux and phux-mcp in PowerShell.
.DESCRIPTION
Uses the existing verified Linux release installer. Requires an initialized
Ubuntu (22.04+) or compatible glibc WSL distribution; does not install WSL,
elevate, change execution policy, or modify PowerShell profiles.
.EXAMPLE
.\install-windows.ps1 -Distribution Ubuntu
.EXAMPLE
.\install-windows.ps1 -Channel next -NoModifyPath
#>
[CmdletBinding()]
param(
    [ValidatePattern('^[A-Za-z0-9][A-Za-z0-9 ._-]*$')]
    [string] $Distribution = 'Ubuntu',
    [ValidateSet('stable', 'next')]
    [string] $Channel = 'stable',
    [ValidatePattern('^v?(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$')]
    [string] $Version,
    [string] $InstallDir = (Join-Path ([Environment]::GetFolderPath('LocalApplicationData')) 'phux\bin'),
    [switch] $NoModifyPath,
    [switch] $DryRun
)

$ErrorActionPreference = 'Stop'

function ConvertTo-PhuxShellLiteral([string] $Value) {
    # POSIX single quoting, including literal apostrophes. Never interpolate
    # caller arguments as shell source.
    if ($Value.Contains([string][char]0)) { throw 'Command arguments cannot contain NUL characters.' }
    return "'" + $Value.Replace("'", "'\''") + "'"
}

function Get-PhuxWslArguments([string] $Distro, [string] $Script) {
    $encoded = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Script))
    # No embedded double quotes cross Windows' native argument boundary. This
    # works with both Windows PowerShell 5.1's legacy quoting and PowerShell 7.
    # Empty IFS and disabled globbing preserve the decoded script as ONE eval
    # argument. The pipe is only for decoding, never the program's stdin.
    return @('--distribution', $Distro, '--exec', 'sh', '-c',
        ('IFS=;set -f;eval $(printf %s ' + $encoded + '|base64 -d)'))
}

function Get-PhuxCommandIndex([string[]] $Arguments) {
    $valueFlags = @('--socket', '--rec', '--rec-format', '--remote')
    $index = 0
    while ($index -lt $Arguments.Count) {
        if ($Arguments[$index] -match '^--(socket|rec|rec-format|remote)=') { $index++; continue }
        if ($valueFlags -contains $Arguments[$index]) { $index += 2; continue }
        break
    }
    return $index
}

function Test-PhuxTui([string] $Tool, [string[]] $Arguments) {
    if ($Tool -ne 'phux') { return $false }
    $headlessFlags = @('--json', '--help', '-h', '--version', '-V', '--skill', '--capabilities')
    foreach ($argument in $Arguments) {
        if ($headlessFlags -contains $argument) { return $false }
    }
    $index = Get-PhuxCommandIndex $Arguments
    if ($index -ge $Arguments.Count) { return $true }
    $verb = $Arguments[$index]
    if (@('attach', 'a', 'new') -contains $verb) { return $true }
    $subcommands = @{ project = 'open'; p = 'open'; host = 'attach'; machine = 'attach' }
    if ($subcommands.ContainsKey($verb)) { return $Arguments[$index + 1] -eq $subcommands[$verb] }
    return $verb -eq 'worktree' -and $Arguments -contains '--attach'
}

function Get-PhuxLauncher([string] $Distro, [string] $Tool) {
    $functions = "function ConvertTo-PhuxShellLiteral {${function:ConvertTo-PhuxShellLiteral}}`n" +
        "function Get-PhuxWslArguments {${function:Get-PhuxWslArguments}}`n" +
        "function Get-PhuxCommandIndex {${function:Get-PhuxCommandIndex}}`n" +
        "function Test-PhuxTui {${function:Test-PhuxTui}}`n"
    $settings = '$distribution = ' + "'" + $Distro.Replace("'", "''") + "'`n" +
        '$tool = ' + "'" + $Tool + "'`n"
    return "#Requires -Version 5.1`n# Generated by phux's WSL installer.`n" + $functions + $settings + @'
$isMcpStdio = $tool -eq 'phux-mcp' -and $args.Count -eq 0
if ($tool -eq 'phux' -and $args.Count -eq 1) { $isMcpStdio = $args[0] -eq 'mcp' }
if ($PSVersionTable.PSVersion.Major -lt 6 -and $isMcpStdio -and -not $MyInvocation.ExpectingInput) {
    if ([Console]::IsInputRedirected) {
        [Console]::Error.WriteLine('For Windows MCP clients, launch wsl.exe --distribution ' + $distribution + ' --exec sh -c "exec ~/.local/bin/phux-mcp" directly. Windows PowerShell 5.1 buffers redirected stdin; PowerShell 7 also supports this launcher.')
        exit 2
    }
}
$script = 'export PATH="$HOME/.local/bin:$PATH";exec "$HOME/.local/bin/' + $tool + '"'
foreach ($argument in $args) {
    $script += ' ' + (ConvertTo-PhuxShellLiteral ([string] $argument))
}
$wslArguments = Get-PhuxWslArguments $distribution $script
$savedEncoding = [Console]::OutputEncoding
$adjustEncoding = $true
if ((Test-PhuxTui $tool $args) -and -not $MyInvocation.ExpectingInput -and
    -not [Console]::IsInputRedirected -and -not [Console]::IsOutputRedirected) {
    # Native WSL owns interactive console I/O. Do not change its code pages
    # while the ConPTY input/output handles are active.
    $adjustEncoding = $false
}
try {
    $utf8 = [Text.UTF8Encoding]::new($false)
    if ($adjustEncoding) { [Console]::OutputEncoding = $utf8 }
    $OutputEncoding = $utf8
    if ($MyInvocation.ExpectingInput) {
        # Windows PowerShell can add a BOM to a native pipe even when the
        # local encoding says not to. Send ASCII base64 records instead; GNU
        # base64 ignores the host's preamble, but preserves all user text.
        $pipeScript = 'base64 --decode --ignore-garbage | sh -c ' + (ConvertTo-PhuxShellLiteral $script)
        $wslArguments = Get-PhuxWslArguments $distribution $pipeScript
        $input | ForEach-Object {
            [Convert]::ToBase64String($utf8.GetBytes(([string] $_) + "`n"))
        } | & wsl.exe @wslArguments
    } else {
        & wsl.exe @wslArguments
    }
    $code = $LASTEXITCODE
} finally {
    if ($adjustEncoding) { [Console]::OutputEncoding = $savedEncoding }
}
exit $code
'@
}

function Add-PhuxUserPath([string] $Directory) {
    $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
    $entries = @($userPath -split ';' | Where-Object { $_ })
    if ($entries -notcontains $Directory) {
        [Environment]::SetEnvironmentVariable('Path', (($entries + $Directory) -join ';'), 'User')
    }
    if (($env:Path -split ';') -notcontains $Directory) {
        $env:Path += ';' + $Directory
    }
}

if ($env:OS -ne 'Windows_NT') {
    throw 'Run this installer in Windows PowerShell. Inside WSL, use https://phux.sh/install instead.'
}
if ($Version -and $Channel -ne 'stable') {
    throw '-Version requires -Channel stable.'
}
if ([string]::IsNullOrWhiteSpace($InstallDir)) {
    throw '-InstallDir must not be empty.'
}
$InstallDir = [IO.Path]::GetFullPath($InstallDir)

$options = '--no-modify-path --install-dir "$HOME/.local/bin" --channel ' + (ConvertTo-PhuxShellLiteral $Channel)
if ($Version) { $options += ' --version ' + (ConvertTo-PhuxShellLiteral $Version) }
$install = @'
set -eu
command -v curl >/dev/null || { echo 'phux: install curl and ca-certificates in this WSL distribution first (sudo apt-get install -y curl ca-certificates)' >&2; exit 1; }
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
curl -fsSL --proto =https --connect-timeout 10 --max-time 120 https://phux.sh/install -o "$work/install.sh"
sh "$work/install.sh"
'@
# Git's Windows checkout may use CRLF; the Linux shell source must use LF.
# Normalize only this static source, never caller argument data.
$install = $install.Replace("`r`n", "`n")
$install += ' ' + $options + "`n" + '"$HOME/.local/bin/phux" --version' + "`n" + '"$HOME/.local/bin/phux-mcp" --version'

if ($DryRun) {
    Write-Output "WSL distribution: $Distribution; channel: $Channel; version: $Version"
    Write-Output "Linux programs: ~/.local/bin/phux and ~/.local/bin/phux-mcp"
    Write-Output "PowerShell launchers: $InstallDir"
    Write-Output "Modify user PATH: $(-not $NoModifyPath)"
    return
}

foreach ($tool in @('phux', 'phux-mcp')) {
    $path = Join-Path $InstallDir ($tool + '.ps1')
    if ((Test-Path -LiteralPath $path) -and
        -not ([IO.File]::ReadAllText($path).Contains('# Generated by phux''s WSL installer.'))) {
        throw "Refusing to overwrite an unrelated file: $path. Choose another -InstallDir."
    }
}

if (-not (Get-Command wsl.exe -ErrorAction SilentlyContinue)) {
    throw 'WSL is required. Run wsl --install -d Ubuntu, restart if requested, then open Ubuntu once to create your Linux user.'
}
$probe = Get-PhuxWslArguments $Distribution 'test "$(id -u)" -ne 0 && test -d "$HOME"'
& wsl.exe @probe
if ($LASTEXITCODE -ne 0) {
    throw "Initialize $Distribution with a non-root default user first: wsl --install -d $Distribution; then open it and create your Linux user. Use -Distribution to select an existing distribution."
}

$installArguments = Get-PhuxWslArguments $Distribution $install
& wsl.exe @installArguments
if ($LASTEXITCODE -ne 0) {
    throw 'The Linux release installation failed; no Windows launchers or PATH changes were made.'
}

[IO.Directory]::CreateDirectory($InstallDir) | Out-Null
$utf8 = [Text.UTF8Encoding]::new($false)
foreach ($tool in @('phux', 'phux-mcp')) {
    $path = Join-Path $InstallDir ($tool + '.ps1')
    [IO.File]::WriteAllText($path, (Get-PhuxLauncher $Distribution $tool), $utf8)
}
if (-not $NoModifyPath) { Add-PhuxUserPath $InstallDir }
Write-Output "Installed phux and phux-mcp PowerShell launchers in $InstallDir (WSL: $Distribution)."
if ($NoModifyPath) {
    Write-Output "PATH was not changed. Invoke phux.ps1 from $InstallDir, or add that directory to PATH."
} else {
    Write-Output 'Open a new PowerShell window, then run phux --version and phux.'
}
Write-Output 'Linux paths and Linux tools apply to phux arguments. Use Windows Terminal for the interactive UI.'
