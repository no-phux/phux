#!/usr/bin/env python3
"""Open a PR in each repository that pins phux's design tokens, moving it to REVISION.

Each consumer owns `scripts/phux-design.py pin <rev>`; this only drives it.
A consumer whose pinned files already match is left alone, so a token-free
change to main opens nothing.
"""
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile

REPOSITORIES = ("website", "phux-org", "phux-hud")
BRANCH = "chore/phux-design-pin"


def run(args, cwd=None):
    return subprocess.check_output(args, cwd=cwd, text=True).strip()


def git(root, *args):
    return run(["git", "-c", "credential.helper=", "-c", "credential.helper=!gh auth git-credential", *args], cwd=root)


def propose(directory, repository, revision):
    root = directory / repository
    git(directory, "clone", "--quiet", "--depth", "1", f"https://github.com/no-phux/{repository}.git", str(root))
    old = json.loads((root / "phux-design.lock.json").read_bytes())["rev"]
    run([sys.executable, "-B", "scripts/phux-design.py", "pin", revision], cwd=root)
    if not run(["git", "status", "--porcelain", "--", ".", ":!phux-design.lock.json"], cwd=root):
        return f"{repository}: tokens unchanged since {old[:12]}"
    git(root, "switch", "-c", BRANCH)
    git(root, "add", "-A")
    git(root, "-c", "user.name=PHUX Design Bot", "-c", "user.email=phux-design[bot]@users.noreply.github.com",
        "-c", "core.hooksPath=/dev/null", "commit", "-m", f"chore(design): pin phux design tokens to {revision[:12]}")
    git(root, "-c", "core.hooksPath=/dev/null", "push", "--force", "origin", BRANCH)
    repo = f"no-phux/{repository}"
    if json.loads(run(["gh", "pr", "list", "--repo", repo, "--head", BRANCH, "--json", "url"])):
        return f"{repository}: updated the open pin PR to {revision[:12]}"
    body = (f"Pin phux design tokens to no-phux/phux@{revision} (was {old[:12]}).\n\n"
            "Generated by phux `tools design-gen`; this repository's CI is the merge gate.\n")
    return run(["gh", "pr", "create", "--repo", repo, "--base", "main", "--head", BRANCH,
                "--title", f"chore(design): pin phux design tokens to {revision[:12]}", "--body", body])


def main():
    revision = sys.argv[1] if len(sys.argv) == 2 else ""
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        sys.exit("usage: design-pin.py <40-hex phux revision>")
    failures = []
    with tempfile.TemporaryDirectory(prefix="phux-design-pin-") as directory:
        for repository in REPOSITORIES:
            try:
                print(propose(Path(directory), repository, revision))
            except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
                failures.append(f"{repository}: {error}")
    if failures:
        sys.exit("\n".join(failures))


if __name__ == "__main__":
    main()
