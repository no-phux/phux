#!/bin/sh
# Assemble the standalone curl | sh installer; sources are build-time only.
set -eu

check=0
case "$#" in
  0) ;;
  1)
    [ "$1" = --check ] || { echo "usage: $0 [--check]" >&2; exit 2; }
    check=1
    ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

ROOT="$(CDPATH='' cd "$(dirname "$0")/.." && pwd)"
source_dir="$ROOT/scripts/installer"
output="$ROOT/scripts/install.sh"
tmp="$(mktemp "${output}.XXXXXX")"
trap 'rm -f "$tmp"' 0
trap 'exit 1' HUP INT TERM

{
  head -n 1 "$source_dir/common.sh"
  printf '%s\n' '# @generated by scripts/generate-install.sh; edit scripts/installer/*.sh instead.'
  tail -n +2 "$source_dir/common.sh"
  cat "$source_dir/cli.sh" "$source_dir/desktop.sh" "$source_dir/rune.sh" "$source_dir/main.sh"
} > "$tmp"

if [ "$check" -eq 1 ]; then
  cmp -s "$tmp" "$output" || {
    echo "scripts/install.sh is stale; run sh scripts/generate-install.sh" >&2
    exit 1
  }
else
  chmod 755 "$tmp"
  mv -f "$tmp" "$output"
fi
