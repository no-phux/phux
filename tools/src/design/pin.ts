// Open a PR in each repository that pins phux's design tokens, moving it to
// a phux revision. Each consumer owns `scripts/phux-design.py pin <rev>`;
// this only drives it. A consumer whose pinned files already match is left
// alone, so a token-free change to main opens nothing.
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, Failure, UsageError } from "../lib/command.ts";
import { capture } from "../lib/process.ts";
import { str, table } from "../lib/value.ts";

export const REPOSITORIES = ["website", "phux-org", "phux-hud", "ops"] as const;
export const BRANCH = "chore/phux-design-pin";

/** Where a consumer is cloned from; tests point it at a local fixture. */
export type Remote = (repository: string) => string;
const GITHUB: Remote = (repository) => `https://github.com/no-phux/${repository}.git`;

// The workflow's app token reaches git through gh, never a stored credential.
const CREDENTIALS = ["-c", "credential.helper=", "-c", "credential.helper=!gh auth git-credential"];
const BOT = [
  "-c",
  "user.name=PHUX Design Bot",
  "-c",
  "user.email=phux-design[bot]@users.noreply.github.com",
];
const NO_HOOKS = ["-c", "core.hooksPath=/dev/null"];

// The live environment: Bun's spawn default is the environment at startup.
const run = (argv: string[], cwd?: string): string =>
  capture(argv, { cwd, env: process.env }).trim();
const git = (cwd: string, ...args: string[]): string => run(["git", ...CREDENTIALS, ...args], cwd);

/** The revision a consumer's lock pins. */
function pinnedRev(root: string): string {
  const rev = str(
    table(JSON.parse(readFileSync(join(root, "phux-design.lock.json"), "utf8")))["rev"],
  );
  if (rev === undefined) throw new Failure("phux-design.lock.json has no rev");
  return rev;
}

/** Pin one consumer to `revision`; returns the line the workflow log shows. */
export function propose(
  directory: string,
  repository: string,
  revision: string,
  remote = GITHUB,
): string {
  const root = join(directory, repository);
  git(directory, "clone", "--quiet", "--depth", "1", remote(repository), root);
  const old = pinnedRev(root);
  run(["python3", "-B", "scripts/phux-design.py", "pin", revision], root);
  if (run(["git", "status", "--porcelain", "--", ".", ":!phux-design.lock.json"], root) === "") {
    return `${repository}: tokens unchanged since ${old.slice(0, 12)}`;
  }
  const short = revision.slice(0, 12);
  const title = `chore(design): pin phux design tokens to ${short}`;
  git(root, "switch", "-c", BRANCH);
  git(root, "add", "-A");
  git(root, ...BOT, ...NO_HOOKS, "commit", "-m", title);
  git(root, ...NO_HOOKS, "push", "--force", "origin", BRANCH);
  const repo = `no-phux/${repository}`;
  const open: unknown = JSON.parse(
    run(["gh", "pr", "list", "--repo", repo, "--head", BRANCH, "--json", "url"]),
  );
  if (Array.isArray(open) && open.length > 0) {
    return `${repository}: updated the open pin PR to ${short}`;
  }
  const body =
    `Pin phux design tokens to no-phux/phux@${revision} (was ${old.slice(0, 12)}).\n\n` +
    "Generated by phux `tools design-gen`; this repository's CI is the merge gate.\n";
  return run([
    "gh",
    "pr",
    "create",
    "--repo",
    repo,
    "--base",
    "main",
    "--head",
    BRANCH,
    "--title",
    title,
    "--body",
    body,
  ]);
}

/** Pin every consumer; one consumer's failure does not stop the others. */
export function designPin(
  revision: string | undefined,
  repositories: readonly string[] = REPOSITORIES,
  remote = GITHUB,
): void {
  if (revision === undefined || !/^[0-9a-f]{40}$/.test(revision)) {
    throw new UsageError("REVISION must be a 40-hex phux revision");
  }
  const directory = mkdtempSync(join(tmpdir(), "phux-design-pin-"));
  const failures: string[] = [];
  try {
    for (const repository of repositories) {
      try {
        console.log(propose(directory, repository, revision, remote));
      } catch (error) {
        failures.push(`${repository}: ${describe(error)}`);
      }
    }
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
  if (failures.length > 0) throw new Failure(failures.join("\n"));
}
